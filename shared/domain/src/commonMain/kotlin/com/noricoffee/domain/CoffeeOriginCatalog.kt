package com.noricoffee.domain

/**
 * 産地の国ドロップダウン用カタログ（コーヒー生産国 ~43 か国 + 特殊項目）。
 *
 * [CoffeeRecord.origin] を自由入力からドロップダウン選択に変更するための、選択肢の
 * **単一の真実点**。iOS ピッカーは SKIE ブリッジ経由でこのカタログを読み、リストを二重管理しない。
 *
 * - `countries` の各要素は [OriginNormalizer.normalize] の正規形（固定点）であること
 *   （新規追加国には英語綴りシノニムも [OriginNormalizer] へ追加し、カバレッジを揃える）
 * - 表示順 = 生産量の概算ランキング順（ICO/FAO ベース。上位は確度が高く小規模産地の相対順は目安）
 *
 * @see [docs/data-model.md] §1.3a
 */
object CoffeeOriginCatalog {

    val countries: List<String> = listOf(
        "ブラジル", "ベトナム", "コロンビア", "インドネシア", "エチオピア", "ウガンダ",
        "インド", "ホンジュラス", "ペルー", "メキシコ", "グアテマラ", "中国",
        "ニカラグア", "コートジボワール", "コスタリカ", "ケニア", "タンザニア", "エルサルバドル",
        "パプアニューギニア", "ラオス", "カメルーン", "タイ", "ベネズエラ", "コンゴ民主共和国",
        "ルワンダ", "ブルンジ", "ハイチ", "エクアドル", "ドミニカ共和国", "フィリピン",
        "ボリビア", "ミャンマー", "キューバ", "ザンビア", "イエメン", "マラウイ",
        "ネパール", "東ティモール", "パナマ", "台湾", "ジャマイカ", "プエルトリコ", "ハワイ",
    )

    /** 複数産地。単一国に落とし込めないコーヒー。literal をそのまま [CoffeeRecord.origin] に保存する。 */
    const val BLEND: String = "ブレンド"

    /** リスト外の産地。UI は選択時に国名の自由入力欄を出す。入力された実国名を保存し literal は保存しない。 */
    const val OTHER: String = "その他"
}
